// Fetches video metadata and timed captions from YouTube without an API key.
// Uses the same InnerTube "player" endpoint the Android app calls; the web
// watch page's caption URLs now require a proof-of-origin token, this one doesn't.

const INNERTUBE_PLAYER_URL = "https://www.youtube.com/youtubei/v1/player?prettyPrint=false";
const ANDROID_CLIENT_VERSION = "20.10.38";

const VIDEO_ID_PATTERN = /^[A-Za-z0-9_-]{11}$/;
// A stuck YouTube request would otherwise hold one of the few ingest slots indefinitely
const REQUEST_TIMEOUT_MS = 15_000;

export interface CaptionSegment {
  start: number; // seconds
  duration: number; // seconds
  text: string;
}

export interface YouTubeVideo {
  videoId: string;
  title: string;
  author: string;
  lengthSeconds: number;
  captionLanguage: string;
  isAutoGenerated: boolean;
  segments: CaptionSegment[];
}

/**
 * YouTube refused this server, not this video. It blocks most cloud and datacenter
 * IPs, so on a hosted deploy every pasted link fails this way; locally it works.
 */
export class YouTubeBlockedError extends Error {}

// Bot checks come back as LOGIN_REQUIRED with a "confirm you're not a bot" reason
function isBotCheck(playability: { status?: string; reason?: string } | undefined): boolean {
  return playability?.status === "LOGIN_REQUIRED" && /bot/i.test(playability.reason ?? "");
}

interface CaptionTrack {
  baseUrl: string;
  languageCode: string;
  kind?: string; // "asr" for auto-generated
}

/**
 * Pull the 11-character video ID out of any common YouTube URL shape, or a bare ID
 */
export function parseYouTubeVideoId(input: string): string | null {
  const trimmed = input.trim();
  if (VIDEO_ID_PATTERN.test(trimmed)) return trimmed;

  let url: URL;
  try {
    url = new URL(trimmed.includes("://") ? trimmed : `https://${trimmed}`);
  } catch {
    return null;
  }

  const host = url.hostname.replace(/^(www\.|m\.|music\.)/, "");
  let candidate: string | null = null;

  if (host === "youtu.be") {
    candidate = url.pathname.split("/")[1] ?? null;
  } else if (host === "youtube.com" || host === "youtube-nocookie.com") {
    if (url.pathname === "/watch") {
      candidate = url.searchParams.get("v");
    } else {
      // /embed/ID, /shorts/ID, /live/ID, /v/ID
      const match = url.pathname.match(/^\/(?:embed|shorts|live|v)\/([^/?#]+)/);
      candidate = match?.[1] ?? null;
    }
  }

  return candidate && VIDEO_ID_PATTERN.test(candidate) ? candidate : null;
}

export async function fetchYouTubeVideo(videoId: string): Promise<YouTubeVideo> {
  const res = await fetch(INNERTUBE_PLAYER_URL, {
    signal: AbortSignal.timeout(REQUEST_TIMEOUT_MS),
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "User-Agent": `com.google.android.youtube/${ANDROID_CLIENT_VERSION} (Linux; U; Android 14)`,
    },
    body: JSON.stringify({
      context: {
        client: {
          clientName: "ANDROID",
          clientVersion: ANDROID_CLIENT_VERSION,
          androidSdkVersion: 34,
          hl: "en",
        },
      },
      videoId,
    }),
  });

  if (res.status === 403 || res.status === 429) {
    throw new YouTubeBlockedError(`YouTube returned ${res.status} while looking up the video`);
  }
  if (!res.ok) {
    throw new Error(`YouTube returned ${res.status} while looking up the video`);
  }

  const player = await res.json();
  const playability = player.playabilityStatus;
  if (isBotCheck(playability)) {
    throw new YouTubeBlockedError(`YouTube won't serve this video (${playability.status}: ${playability.reason})`);
  }
  if (playability?.status !== "OK") {
    throw new Error(
      `YouTube won't serve this video (${playability?.status ?? "unknown"}${
        playability?.reason ? `: ${playability.reason}` : ""
      })`
    );
  }

  const tracks: CaptionTrack[] =
    player.captions?.playerCaptionsTracklistRenderer?.captionTracks ?? [];
  const track = pickCaptionTrack(tracks);
  if (!track) {
    throw new Error("This video has no captions, so there's no transcript to search");
  }

  // Drop any fmt param so YouTube returns the plain <transcript><text> XML
  const captionRes = await fetch(track.baseUrl.replace(/&fmt=[^&]*/, ""), {
    signal: AbortSignal.timeout(REQUEST_TIMEOUT_MS),
  });
  if (captionRes.status === 403 || captionRes.status === 429) {
    throw new YouTubeBlockedError(`YouTube returned ${captionRes.status} while fetching captions`);
  }
  if (!captionRes.ok) {
    throw new Error(`YouTube returned ${captionRes.status} while fetching captions`);
  }
  const segments = parseCaptionXml(await captionRes.text());
  if (segments.length === 0) {
    throw new Error("The caption track came back empty");
  }

  const details = player.videoDetails ?? {};
  if (details.isLive || details.isUpcoming) {
    throw new Error("This is a live or upcoming stream. Try again once it has finished and has captions");
  }
  return {
    videoId,
    title: details.title ?? videoId,
    author: details.author ?? "Unknown channel",
    lengthSeconds: Number(details.lengthSeconds) || 0,
    captionLanguage: track.languageCode,
    isAutoGenerated: track.kind === "asr",
    segments,
  };
}

/**
 * Prefer human-written English, then auto-generated English, then anything
 */
function pickCaptionTrack(tracks: CaptionTrack[]): CaptionTrack | undefined {
  const isEnglish = (t: CaptionTrack) => t.languageCode.toLowerCase().startsWith("en");
  return (
    tracks.find((t) => isEnglish(t) && t.kind !== "asr") ??
    tracks.find(isEnglish) ??
    tracks.find((t) => t.kind !== "asr") ??
    tracks[0]
  );
}

function parseCaptionXml(xml: string): CaptionSegment[] {
  const segments: CaptionSegment[] = [];
  const textTag = /<text start="([\d.]+)"(?: dur="([\d.]+)")?[^>]*>([\s\S]*?)<\/text>/g;

  let match;
  while ((match = textTag.exec(xml)) !== null) {
    // Caption text arrives double-encoded (&amp;#39;), so decode twice
    const text = decodeEntities(decodeEntities(match[3]))
      .replace(/<[^>]+>/g, "")
      .replace(/\s+/g, " ")
      .trim();
    if (!text) continue;
    segments.push({
      start: Number(match[1]),
      duration: Number(match[2] ?? 0),
      text,
    });
  }

  return segments;
}

function decodeEntities(text: string): string {
  return text
    .replace(/&#(\d+);/g, (_, code) => String.fromCodePoint(Number(code)))
    .replace(/&#x([0-9a-f]+);/gi, (_, code) => String.fromCodePoint(parseInt(code, 16)))
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&amp;/g, "&");
}
